const ENDINGS = [
  'иями', 'ями', 'ами', 'иях', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ах', 'ях', 'ов', 'ев', 'ей', 'ой', 'ий', 'ый',
  'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ую', 'юю', 'ом', 'ем', 'ам', 'ям', 'их', 'ых', 'а', 'я', 'ы', 'и', 'у', 'ю', 'о', 'е', 'ь', 'й',
]

/** Грубый русский стеммер: «курицей» → «куриц», «картошки» → «картошк». */
export function stem(word: string): string {
  let w = word.toLowerCase().replace(/ё/g, 'е')
  if (w.length <= 3) return w
  for (const e of ENDINGS) {
    if (w.length - e.length >= 3 && w.endsWith(e)) {
      w = w.slice(0, -e.length)
      break
    }
  }
  return w
}

export function tokenize(s: string): string[] {
  return s.toLowerCase().replace(/ё/g, 'е').split(/[^a-zа-я0-9]+/).filter(Boolean)
}

// Служебные слова не ищем: иначе «безе» → «без» и находится всё «без масла».
const STOP = new Set(['без', 'для', 'при', 'под', 'над', 'или', 'как', 'на', 'в', 'во', 'с', 'со', 'и', 'по', 'из', 'от', 'до', 'за', 'к', 'ко', 'у', 'о', 'об', 'не'])

// Разные слова одного продукта → одна основа: «картошка фри» = «картофель фри».
const SEARCH_SYN: Record<string, string> = {
  картошк: 'картофел',
  картофельн: 'картофел',
  картоф: 'картофел',
  помидор: 'томат',
  цукин: 'кабачк',
  кабачок: 'кабачк',
  курин: 'куриц',
  цыплят: 'куриц',
  цыпленк: 'куриц',
  индюш: 'индейк',
  говяж: 'говядин',
  свин: 'свинин',
  свиной: 'свинин',
  семг: 'лосос',
  крыл: 'крыл',
  крылышк: 'крыл',
  крылыш: 'крыл',
  крыль: 'крыл',
}

/** Термин для поискового индекса и запроса: без служебных слов, с основой и синонимами. */
export function searchTerm(term: string): string | null {
  const w = term.toLowerCase().replace(/ё/g, 'е')
  if (STOP.has(w)) return null
  let s = stem(w)
  if (STOP.has(s)) s = w // «безе» не превращаем в «без»
  return SEARCH_SYN[s] ?? s
}
